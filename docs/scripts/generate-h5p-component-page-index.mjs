#!/usr/bin/env node
/**
 * Generate shipped-block → component page links for the H5P capability map.
 * Run: node docs/scripts/generate-h5p-component-page-index.mjs
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const manifestPath = join(root, "docs/component-demos/manifest.json");
const outPath = join(root, "docs/_generated/h5p-component-pages.md");

const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));

const slugByType = new Map();
for (const entry of manifest.components) {
  if (entry.blockType) slugByType.set(entry.blockType, entry.slug);
}
slugByType.set("Text", "text-and-heading");
slugByType.set("Heading", "text-and-heading");
slugByType.set("Course", "course-structure");
slugByType.set("Lesson", "course-structure");
slugByType.set("ProgressTracker", "course-structure");

/** Rows: [LessonKit id(s), H5P display name] — shipped blocks with pages */
const SHIPPED = [
  ["Quiz", "Multiple Choice"],
  ["KnowledgeCheck", "Multiple Choice (alias)"],
  ["TrueFalse", "True/False"],
  ["FillInTheBlanks", "Fill in the Blanks"],
  ["DragAndDrop", "Drag and Drop"],
  ["DragTheWords", "Drag the Words"],
  ["MarkTheWords", "Mark the Words"],
  ["Summary", "Summary"],
  ["ArithmeticQuiz", "Arithmetic Quiz"],
  ["Essay", "Essay"],
  ["Questionnaire", "Questionnaire"],
  ["AssessmentSequence", "Question Set"],
  ["Scenario", "Scenario (narrative)"],
  ["Reflection", "Reflection"],
  ["InteractiveBook", "Interactive Book"],
  ["Page", "Column / Page"],
  ["SlideDeck", "Course Presentation"],
  ["Slide", "Course Presentation (slide)"],
  ["InteractiveVideo", "Interactive Video"],
  ["TimedCue", "Interactive Video (cue)"],
  ["BranchingScenario", "Branching Scenario"],
  ["BranchNode", "Branching Scenario (node)"],
  ["BranchChoice", "Branching Scenario (choice)"],
  ["GameMap", "Game Map"],
  ["MapStage", "Game Map (stage)"],
  ["MapExit", "Game Map (exit)"],
  ["ImageHotspots", "Image Hotspots"],
  ["FindHotspot", "Find the Hotspot"],
  ["FindMultipleHotspots", "Find Multiple Hotspots"],
  ["ImageSlider", "Image Slider"],
  ["ImageJuxtaposition", "Image Juxtaposition"],
  ["ImageSequence", "Agamotto (frames)"],
  ["Collage", "Collage"],
  ["ImagePairing", "Image Pairing"],
  ["ImageSequencing", "Image Sequencing"],
  ["MemoryGame", "Memory Game"],
  ["Embed", "Iframe Embedder"],
  ["Chart", "Chart"],
  ["Accordion", "Accordion"],
  ["DialogCards", "Dialog Cards"],
  ["Flashcards", "Flashcards"],
  ["Timeline", "Timeline"],
  ["Table", "Table"],
  ["InformationWall", "Information Wall"],
  ["AudioRecorder", "Audio Recorder"],
  ["ParallaxSlideshow", "Slideshow (parallax)"],
  ["Crossword", "Crossword"],
  ["WordSearch", "Find the Words"],
  ["CombinationLock", "Combination Lock"],
  ["QrContent", "KewAr Code"],
  ["AdventCalendar", "Advent Calendar"],
  ["Video", "Self-hosted video"],
  ["Image", "Image"],
  ["Text", "Text / Heading"],
];

function link(type, label) {
  const slug = slugByType.get(type);
  if (!slug) return label;
  return `[\`${type}\`](../reference/components/${slug}.md)`;
}

const lines = [
  "<!-- Generated by docs/scripts/generate-h5p-component-page-index.mjs -->",
  "",
  "## Component pages (live demos)",
  "",
  "Shipped blocks below have a **Read the Docs** page with an embedded demo, usage guidance, and examples. Full index: [Component pages](../reference/components/index.md).",
  "",
  "| LessonKit | H5P-style name | Demo & guide |",
  "| --- | --- | --- |",
];

for (const [type, h5p] of SHIPPED) {
  lines.push(`| ${type} | ${h5p} | ${link(type, "Open →")} |`);
}

lines.push("");

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, `${lines.join("\n")}\n`);
console.log(`Wrote ${outPath} (${SHIPPED.length} rows)`);
