#!/usr/bin/env node
/**
 * Generate per-block prop tables from block-catalog.v3.json for Sphinx docs.
 * Run: node docs/scripts/generate-block-props-doc.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const catalogPath = join(root, "packages/react/block-catalog.v3.json");
const outDir = join(root, "docs/_generated");
const outPath = join(outDir, "block-props.md");

const catalog = JSON.parse(readFileSync(catalogPath, "utf8"));

const COMPOUND_TYPES = new Set([
  "InteractiveBook",
  "SlideDeck",
  "InteractiveVideo",
  "BranchingScenario",
  "AssessmentSequence",
  "Page",
  "Slide",
  "TimedCue",
  "BranchNode",
  "BranchChoice",
]);

const STORYBOOK = {
  InteractiveBook: "https://eddiethedean.github.io/lessonkit/storybook/?path=/story/components-compound-tier-c-d--interactive-book-block",
  SlideDeck: "https://eddiethedean.github.io/lessonkit/storybook/?path=/story/components-compound-tier-c-d--slide-deck-block",
  InteractiveVideo: "https://eddiethedean.github.io/lessonkit/storybook/?path=/story/components-compound-tier-c-d--interactive-video-block",
  BranchingScenario: "https://eddiethedean.github.io/lessonkit/storybook/?path=/story/components-compound-tier-c-d--branching-scenario-block",
  TrueFalse: "https://eddiethedean.github.io/lessonkit/storybook/?path=/story/components-truefalse--default",
  Quiz: "https://eddiethedean.github.io/lessonkit/storybook/?path=/story/components-quiz--unanswered",
};

function escapeCell(s) {
  return String(s).replace(/\|/g, "\\|").replace(/\n/g, " ");
}

const lines = [
  "<!-- Generated by docs/scripts/generate-block-props-doc.mjs — do not edit -->",
  "",
  "# Generated block prop reference (catalog v3)",
  "",
  "Auto-generated from `@lessonkit/react/block-catalog.v3.json`. Regenerate: `node docs/scripts/generate-block-props-doc.mjs`.",
  "",
];

for (const entry of catalog.entries) {
  if (!entry.props?.length) continue;
  // Skip v1 blocks with manual docs in BLOCK_CATALOG.md
  if (["Course", "Lesson", "Scenario", "Reflection", "Quiz", "KnowledgeCheck", "ProgressTracker"].includes(entry.type)) {
    continue;
  }

  lines.push(`## ${entry.type}`);
  lines.push("");
  if (entry.description) lines.push(entry.description);
  lines.push("");

  if (STORYBOOK[entry.type]) {
    lines.push(`**Storybook:** [${entry.type} demo](${STORYBOOK[entry.type]})`);
    lines.push("");
  }

  lines.push("| Prop | Type | Required | Description |");
  lines.push("| --- | --- | --- | --- |");
  for (const prop of entry.props) {
    lines.push(
      `| \`${prop.name}\` | ${escapeCell(prop.type)} | ${prop.required ? "yes" : "no"} | ${escapeCell(prop.description ?? "")} |`,
    );
  }
  lines.push("");

  if (entry.requiredIds?.length) {
    lines.push(`**Required IDs:** ${entry.requiredIds.map((id) => `\`${id}\``).join(", ")}`);
    lines.push("");
  }

  if (entry.telemetry?.emits?.length) {
    lines.push(`**Telemetry:** ${entry.telemetry.emits.map((e) => `\`${e}\``).join(", ")}`);
    lines.push("");
  }

  if (COMPOUND_TYPES.has(entry.type)) {
    lines.push("**Compound:** Implements session resume when `config.session.persistCompoundState` is true. See [Core reference — compound state](reference/core.md#compound-state-and-resume).");
    lines.push("");
  }
}

mkdirSync(outDir, { recursive: true });
writeFileSync(outPath, lines.join("\n"));
console.log(`Wrote ${outPath} (${catalog.entries.length} catalog entries)`);
